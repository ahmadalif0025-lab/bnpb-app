(function() {
    const STORAGE_KEY = 'bnpb_app_data_v1';

    function getStore() {
        const raw = localStorage.getItem(STORAGE_KEY);
        if (raw) {
            try { return JSON.parse(raw); } catch (e) {}
        }
        const initial = JSON.parse(JSON.stringify(window.BNPB_INITIAL_DATA || {}));
        localStorage.setItem(STORAGE_KEY, JSON.stringify(initial));
        return initial;
    }

    function saveStore(data) {
        localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
    }

    window.ClientStorage = {
        async handle(endpoint, options = {}) {
            const method = (options.method || 'GET').toUpperCase();
            const [path, queryString] = endpoint.split('?');
            const params = new URLSearchParams(queryString || '');
            const store = getStore();

            // 1. Dashboard
            if (path.includes('dashboard.php')) {
                const action = params.get('action') || 'summary';
                const bencanaList = store.bencana || [];
                const poskoList = store.posko || [];
                const relawanList = store.relawan || [];

                if (action === 'summary') {
                    let totalMeninggal = 0, totalHilang = 0, totalLukaBerat = 0, totalLukaRingan = 0;
                    let totalMengungsi = 0, totalRumahRusak = 0, totalKerugian = 0;

                    bencanaList.forEach(b => {
                        totalMeninggal += parseInt(b.meninggal || 0);
                        totalHilang += parseInt(b.hilang || 0);
                        totalLukaBerat += parseInt(b.luka_berat || 0);
                        totalLukaRingan += parseInt(b.luka_ringan || 0);
                        totalMengungsi += parseInt(b.mengungsi || 0);
                        totalRumahRusak += parseInt(b.rumah_rusak_berat || 0) + parseInt(b.rumah_rusak_sedang || 0) + parseInt(b.rumah_rusak_ringan || 0);
                        totalKerugian += parseFloat(b.kerugian_estimasi || 0);
                    });

                    const poskoAktif = poskoList.filter(p => p.status === 'aktif').length;
                    const relawanAktif = relawanList.filter(r => r.status === 'aktif').length;
                    const pengungsiAktif = poskoList.filter(p => p.status === 'aktif').reduce((a, c) => a + parseInt(c.jumlah_pengungsi || 0), 0);
                    const bencanaAktif = bencanaList.filter(b => b.status !== 'selesai').length;

                    return {
                        success: true,
                        data: {
                            total_bencana: bencanaList.length,
                            bencana_aktif: bencanaAktif,
                            posko_aktif: poskoAktif,
                            relawan_aktif: relawanAktif,
                            pengungsi_aktif: pengungsiAktif,
                            korban: {
                                meninggal: totalMeninggal,
                                hilang: totalHilang,
                                luka_berat: totalLukaBerat,
                                luka_ringan: totalLukaRingan,
                                mengungsi: totalMengungsi,
                                rumah_rusak: totalRumahRusak,
                                total_kerugian: totalKerugian
                            }
                        }
                    };
                }

                if (action === 'bencana_per_jenis') {
                    const counts = {};
                    (store.jenis_bencana || []).forEach(j => {
                        counts[j.nama_jenis] = { nama_jenis: j.nama_jenis, warna: j.warna || '#3b82f6', ikon: j.ikon, total: 0 };
                    });
                    bencanaList.forEach(b => {
                        if (counts[b.nama_jenis]) counts[b.nama_jenis].total++;
                        else counts[b.nama_jenis] = { nama_jenis: b.nama_jenis, warna: b.warna || '#3b82f6', ikon: b.ikon, total: 1 };
                    });
                    return { success: true, data: Object.values(counts) };
                }

                if (action === 'bencana_per_provinsi') {
                    const counts = {};
                    bencanaList.forEach(b => {
                        counts[b.nama_provinsi] = (counts[b.nama_provinsi] || 0) + 1;
                    });
                    const res = Object.entries(counts).map(([nama_provinsi, total]) => ({ nama_provinsi, total })).sort((a,b) => b.total - a.total);
                    return { success: true, data: res };
                }

                if (action === 'bencana_per_bulan') {
                    const year = params.get('year') || '2026';
                    const monthly = Array.from({ length: 12 }, (_, i) => ({ bulan: i + 1, total: 0 }));
                    bencanaList.forEach(b => {
                        if (b.tanggal_kejadian && b.tanggal_kejadian.startsWith(year)) {
                            const m = parseInt(b.tanggal_kejadian.split('-')[1]) - 1;
                            if (m >= 0 && m < 12) monthly[m].total++;
                        }
                    });
                    return { success: true, data: monthly };
                }

                if (action === 'bencana_terbaru') {
                    const limit = parseInt(params.get('limit') || '5');
                    const sorted = [...bencanaList].sort((a, b) => new Date(b.tanggal_kejadian) - new Date(a.tanggal_kejadian)).slice(0, limit);
                    return { success: true, data: sorted };
                }
            }

            // 2. Bencana CRUD
            if (path.includes('bencana.php')) {
                if (method === 'GET') {
                    const id = params.get('id');
                    if (id) {
                        const item = store.bencana.find(b => String(b.id) === String(id));
                        if (!item) throw new Error('Data bencana tidak ditemukan');
                        const detail = { ...item };
                        detail.posko = (store.posko || []).filter(p => String(p.bencana_id) === String(id));
                        detail.logistik = (store.logistik || []).filter(l => String(l.bencana_id) === String(id));
                        detail.relawan = (store.relawan || []).filter(r => String(r.bencana_id) === String(id));
                        return { success: true, data: detail };
                    }

                    let list = [...(store.bencana || [])];
                    const search = params.get('search');
                    const status = params.get('status');
                    const jenis = params.get('jenis');
                    const prov = params.get('provinsi_id');
                    const kab = params.get('kabkota_id');

                    if (search) {
                        const q = search.toLowerCase();
                        list = list.filter(b => 
                            (b.judul && b.judul.toLowerCase().includes(q)) ||
                            (b.kode_bencana && b.kode_bencana.toLowerCase().includes(q)) ||
                            (b.nama_provinsi && b.nama_provinsi.toLowerCase().includes(q)) ||
                            (b.nama_kabkota && b.nama_kabkota.toLowerCase().includes(q))
                        );
                    }
                    if (status) list = list.filter(b => b.status === status);
                    if (jenis) list = list.filter(b => String(b.jenis_bencana_id) === String(jenis));
                    if (prov) list = list.filter(b => String(b.provinsi_id) === String(prov));
                    if (kab) list = list.filter(b => String(b.kabkota_id) === String(kab));

                    list.sort((a, b) => new Date(b.tanggal_kejadian) - new Date(a.tanggal_kejadian));

                    return {
                        success: true,
                        data: list,
                        pagination: { total: list.length, page: 1, limit: 50, total_pages: 1 }
                    };
                }

                if (method === 'POST') {
                    const body = typeof options.body === 'string' ? JSON.parse(options.body) : (options.body || {});
                    const maxId = store.bencana.reduce((m, b) => Math.max(m, parseInt(b.id) || 0), 0);
                    const newId = maxId + 1;
                    const prov = (store.provinsi || []).find(p => String(p.id) === String(body.provinsi_id));
                    const kab = (store.kabupaten_kota || []).find(k => String(k.id) === String(body.kabkota_id));
                    const jb = (store.jenis_bencana || []).find(j => String(j.id) === String(body.jenis_bencana_id));

                    const year = new Date().getFullYear();
                    const newBencana = {
                        id: newId,
                        kode_bencana: `BNC-${year}-${String(newId).padStart(3, '0')}`,
                        jenis_bencana_id: body.jenis_bencana_id,
                        provinsi_id: body.provinsi_id,
                        kabkota_id: body.kabkota_id,
                        judul: body.judul,
                        deskripsi: body.deskripsi || '',
                        tanggal_kejadian: body.tanggal_kejadian,
                        waktu_kejadian: body.waktu_kejadian || '00:00:00',
                        tingkat_kerusakan: body.tingkat_kerusakan || 'ringan',
                        status: body.status || 'terjadi',
                        nama_jenis: jb?.nama_jenis || 'Lainnya',
                        warna: jb?.warna || '#3b82f6',
                        ikon: jb?.ikon || 'fa-triangle-exclamation',
                        nama_provinsi: prov?.nama_provinsi || 'Jawa Barat',
                        nama_kabkota: kab?.nama_kabupaten || 'Kabupaten',
                        nama_negara: 'Indonesia',
                        meninggal: body.korban?.meninggal || 0,
                        hilang: body.korban?.hilang || 0,
                        luka_berat: body.korban?.luka_berat || 0,
                        luka_ringan: body.korban?.luka_ringan || 0,
                        mengungsi: body.korban?.mengungsi || 0,
                        rumah_rusak_berat: body.korban?.rumah_rusak_berat || 0,
                        rumah_rusak_sedang: body.korban?.rumah_rusak_sedang || 0,
                        rumah_rusak_ringan: body.korban?.rumah_rusak_ringan || 0,
                        kerugian_estimasi: body.korban?.kerugian_estimasi || 0
                    };

                    store.bencana.unshift(newBencana);
                    saveStore(store);
                    return { success: true, message: 'Data bencana berhasil ditambahkan', data: { id: newId } };
                }

                if (method === 'DELETE') {
                    const id = params.get('id');
                    store.bencana = (store.bencana || []).filter(b => String(b.id) !== String(id));
                    saveStore(store);
                    return { success: true, message: 'Data bencana berhasil dihapus' };
                }
            }

            // 3. Referensi
            if (path.includes('referensi.php')) {
                const type = params.get('type');
                if (type === 'indonesia' || type === 'negara') {
                    return { success: true, data: store.indonesia || [] };
                }
                if (type === 'provinsi') {
                    return { success: true, data: store.provinsi || [] };
                }
                if (type === 'kabupaten_kota') {
                    const provId = params.get('provinsi_id');
                    let list = store.kabupaten_kota || [];
                    if (provId) list = list.filter(k => String(k.provinsi_id) === String(provId));
                    return { success: true, data: list };
                }
                if (type === 'jenis_bencana') {
                    return { success: true, data: store.jenis_bencana || [] };
                }
                if (type === 'wilayah_tree') {
                    const negara = (store.indonesia || [])[0] || { id: 1, nama_negara: 'Indonesia' };
                    const provList = (store.provinsi || []).map(p => {
                        const kabs = (store.kabupaten_kota || []).filter(k => String(k.provinsi_id) === String(p.id));
                        const bcs = (store.bencana || []).filter(b => String(b.provinsi_id) === String(p.id)).length;
                        return {
                            ...p,
                            kabupaten_kota: kabs.map(k => ({
                                ...k,
                                total_bencana: (store.bencana || []).filter(b => String(b.kabkota_id) === String(k.id)).length
                            })),
                            total_kabupaten: kabs.length,
                            total_bencana: bcs
                        };
                    });
                    negara.provinsi = provList;
                    negara.total_provinsi = provList.length;
                    negara.total_kabupaten = (store.kabupaten_kota || []).length;
                    return { success: true, data: [negara] };
                }
            }

            // 4. Wilayah
            if (path.includes('wilayah.php')) {
                const action = params.get('action') || 'tree';
                if (action === 'summary') {
                    const provsWithDisaster = new Set((store.bencana || []).map(b => b.provinsi_id));
                    const kabsWithDisaster = new Set((store.bencana || []).map(b => b.kabkota_id).filter(Boolean));
                    return {
                        success: true,
                        data: {
                            total_negara: (store.indonesia || []).length || 1,
                            total_provinsi: (store.provinsi || []).length || 20,
                            total_kabupaten: (store.kabupaten_kota || []).length || 68,
                            provinsi_terdampak: provsWithDisaster.size,
                            kabupaten_terdampak: kabsWithDisaster.size
                        }
                    };
                }
                if (action === 'tree') {
                    return this.handle('referensi.php?type=wilayah_tree', options);
                }
            }

            // 5. Posko, Logistik, Relawan
            if (path.includes('posko.php')) return { success: true, data: store.posko || [] };
            if (path.includes('logistik.php')) return { success: true, data: store.logistik || [] };
            if (path.includes('relawan.php')) return { success: true, data: store.relawan || [] };

            throw new Error(`Endpoint '${path}' tidak dikenali`);
        }
    };
})();

